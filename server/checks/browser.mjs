import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { tmpdir } from 'node:os'
import { mkdir } from 'node:fs/promises'
const root = fileURLToPath(new URL('../..', import.meta.url))
const artifacts = resolve(process.env.BROWSER_ARTIFACTS ?? resolve(tmpdir(), 'quizzent-browser-checks'))
await mkdir(artifacts, { recursive: true })
const { Client, Pool } = await import('pg')
const { runner } = await import('node-pg-migrate')
const { createServer: createVite } = await import('vite')
const { chromium } = await import('playwright-core')
const { createQuizzentServer } = await import(root + '/server/src/server.ts')
const { bootstrapSuperadmin } = await import(root + '/server/src/features/admin/admin.service.ts')
const { createOrganiser } = await import(root + '/server/src/features/auth/signup.service.ts')
const { createCompetition } = await import(root + '/server/src/features/competitions/competition.service.ts')
const { saveQuestion } = await import(root + '/server/src/features/questions/question.service.ts')
const { publishCompetition } = await import(root + '/server/src/features/competitions/publication.service.ts')
const { createRoom, closeRoom } = await import(root + '/server/src/features/rooms/room.service.ts')
const { cancelRoom } = await import(root + '/server/src/features/rooms/cancellation.service.ts')
const schema = 'quizzent_ui_' + randomUUID().replaceAll('-', '')
const connectionString = process.env.DATABASE_URL
const db = new Client({ connectionString })
await db.connect()
let pool, runtime, vite, browser
try {
  await db.query('CREATE SCHEMA "' + schema + '"')
  await runner({ dbClient: db, dir: resolve(root, 'server/migrations'), migrationsTable: 'pgmigrations', migrationsSchema: schema, schema, direction: 'up', log: () => {}, verbose: false })
  pool = new Pool({ connectionString, options: '-c search_path=' + schema, max: 5 })
  const password = 'disposable browser test passphrase'
  const adminAccount = await createOrganiser(pool, { displayName: 'Admin Fixture', email: 'admin@example.test', password })
  const host = await createOrganiser(pool, { displayName: 'Room Host', email: 'host@example.test', password })
  const candidate = await createOrganiser(pool, { displayName: 'Candidate', email: 'candidate@example.test', password })
  await bootstrapSuperadmin(pool, adminAccount.email)
  const competition = await createCompetition(pool, host.id, { title: 'Room History', description: '', questionTimeSeconds: 10 })
  await saveQuestion(pool, host.id, competition.id, { prompt: 'Pick A', options: ['A', 'B', 'C', 'D'], correctOptionIndex: 0 })
  await publishCompetition(pool, host.id, competition.id)
  const closed = await createRoom(pool, host.id, competition.id, 'open')
  await closeRoom(pool, host.id, closed.id)
  const cancelled = await createRoom(pool, host.id, competition.id, 'open')
  await cancelRoom(pool, host.id, cancelled.id, 'Testing cancellation')
  await pool.query(
    "INSERT INTO competitions (organiser_id, title) SELECT $1, 'Practice ' || number FROM generate_series(1, 24) number",
    [host.id],
  )
  await createCompetition(pool, candidate.id, { title: 'Candidate Practice', description: '', questionTimeSeconds: 10 })
  runtime = createQuizzentServer(pool)
  await runtime.start(0)
  const target = 'http://127.0.0.1:' + runtime.server.address().port
  vite = await createVite({ server: { host: '127.0.0.1', port: 0, strictPort: true, proxy: { '/api': { target }, '/socket.io': { target, ws: true } } }, cacheDir: resolve(artifacts, 'vite-cache'), logLevel: 'silent' })
  await vite.listen()
  browser = await chromium.launch({ ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : { channel: process.env.BROWSER_CHANNEL ?? 'msedge' }), headless: true })
  const base = 'http://127.0.0.1:' + vite.httpServer.address().port
  const admin = await browser.newPage({ viewport: { width: 1280, height: 1000 } })
  const organiser = await browser.newPage({ viewport: { width: 375, height: 815 } })
  const errors = []
  for (const page of [admin, organiser]) {
    page.setDefaultTimeout(12_000)
    page.on('pageerror', error => errors.push(error.message))
  }
  async function audit(page, name) {
    await page.addScriptTag({ path: fileURLToPath(import.meta.resolve('axe-core/axe.min.js')) })
    const result = await page.evaluate(async () => axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } }))
    const violations = result.violations.map(item => ({ id: item.id, impact: item.impact, nodes: item.nodes.map(node => ({ target: node.target, summary: node.failureSummary })) }))
    console.log('Accessibility', name, JSON.stringify(violations))
    assert.deepEqual(violations, [], name)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), name + ' overflow')
  }
  async function login(page, email) {
    await page.goto(base + '/login')
    await page.getByLabel('Email address').fill(email)
    await page.getByLabel('Password').fill(password)
    await page.getByRole('button', { name: 'Log in', exact: true }).click()
    await page.waitForURL('**/organiser')
  }
  await organiser.goto(base)
  await organiser.getByRole('link', { name: /Host a quiz/ }).waitFor()
  await organiser.getByText('Sample 1 of 2', { exact: true }).waitFor()
  await organiser.getByText('Sample 2 of 2', { exact: true }).waitFor()
  await organiser.getByRole('button', { name: 'Pause preview', exact: true }).click()
  assert.equal(await organiser.locator('link[rel=icon]').getAttribute('href'), '/favicon.svg')
  assert.equal(await organiser.locator('header img').getAttribute('src'), '/favicon.svg')
  assert.equal((await organiser.request.get(base + '/favicon.svg')).status(), 200)
  await organiser.emulateMedia({ reducedMotion: 'reduce' })
  await organiser.getByRole('button', { name: 'Next sample', exact: true }).click()
  await audit(organiser, 'Home mobile reduced motion')
  await organiser.goto(base + '/signup')
  await audit(organiser, 'Signup mobile')
  await organiser.goto(base + '/login')
  await audit(organiser, 'Login mobile')
  await login(organiser, host.email)
  for (const route of ['/', '/join', '/signup']) {
    await organiser.goto(base + route)
    if (route === '/signup') await organiser.waitForURL('**/organiser')
    await organiser.getByRole('button', { name: 'Log out', exact: true }).waitFor()
    assert.equal(await organiser.locator('a[href="/signup"]').count(), 0)
  }
  await login(admin, adminAccount.email)
  const navigation = admin.getByRole('navigation', { name: 'Main navigation' })
  await navigation.getByRole('link', { name: 'Directory', exact: true }).click()
  await admin.getByRole('table').waitFor()
  assert.equal(await admin.locator('tbody tr').count(), 10)
  await audit(admin, 'Admin directory desktop')
  await admin.getByRole('button', { name: 'Next', exact: true }).click()
  await admin.getByText('Page 2 of 3 · 28 records', { exact: true }).waitFor()
  await admin.getByLabel('Rows per page').selectOption('25')
  await admin.getByText('Page 1 of 2 · 28 records', { exact: true }).waitFor()
  assert.equal(await admin.locator('tbody tr').count(), 25)
  await admin.getByRole('button', { name: /Organisers All organisers/ }).click()
  async function checkOptionArea(page, touch = false) {
    const option = page.locator('label').filter({ hasText: 'Room Host · host@example.test' })
    const checkbox = page.getByRole('checkbox', { name: /Room Host/ })
    const search = page.getByLabel('Find organisers')
    async function assertOpen() {
      assert.equal(await page.getByRole('button', { name: /^Organisers / }).getAttribute('aria-expanded'), 'true')
      assert.ok(await search.isVisible())
    }
    // Start with focus in search, then click padding rather than the checkbox or text.
    for (const area of ['padding', 'text', 'right edge']) {
      await search.focus()
      const box = await option.boundingBox()
      assert.ok(box)
      const target = area === 'text' ? option.locator('span') : option
      const position = area === 'padding' ? { x: 2, y: 2 } : area === 'right edge' ? { x: box.width - 3, y: box.height / 2 } : undefined
      await target[touch ? 'tap' : 'click']({ position })
      assert.ok(await checkbox.isChecked(), `${area} selects the organiser`)
      await assertOpen()
      await target[touch ? 'tap' : 'click']({ position })
      assert.equal(await checkbox.isChecked(), false, `${area} deselects the organiser`)
      await assertOpen()
    }
    await checkbox.focus()
    await page.keyboard.press('Space')
    assert.ok(await checkbox.isChecked())
    await page.getByRole('checkbox', { name: /Candidate/ }).check()
    assert.ok(await checkbox.isChecked(), 'Selecting a second organiser preserves the first')
    await assertOpen()
    await page.getByRole('heading', { name: 'Competitions and rooms' }).click()
    await search.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: /^Organisers / }).click()
    assert.ok(await checkbox.isChecked(), 'Reopening retains the selection')
    await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
    await assertOpen()
    await checkbox.focus()
    await page.keyboard.press('Escape')
    await search.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: /Organisers All organisers/ }).click()
    // Non-control content inside the panel must not dismiss it either.
    await page.locator('label').filter({ hasText: 'Find organisers' }).click()
    await assertOpen()
  }
  await checkOptionArea(admin)
  const touchAdmin = await browser.newPage({ viewport: { width: 375, height: 815 }, isMobile: true, hasTouch: true,
    storageState: await admin.context().storageState() })
  touchAdmin.setDefaultTimeout(12_000)
  touchAdmin.on('pageerror', error => errors.push(error.message))
  await touchAdmin.goto(base + '/admin/directory')
  await touchAdmin.getByRole('button', { name: /Organisers All organisers/ }).click()
  await checkOptionArea(touchAdmin, true)
  await touchAdmin.close()
  const hostLabel = admin.locator('label').filter({ hasText: 'Room Host · host@example.test' })
  await hostLabel.locator('span').click()
  assert.ok(await admin.getByRole('checkbox', { name: /Room Host/ }).isChecked())
  await admin.getByLabel('Find organisers').waitFor()
  await hostLabel.locator('span').click()
  assert.equal(await admin.getByRole('checkbox', { name: /Room Host/ }).isChecked(), false)
  await hostLabel.locator('span').click()
  assert.ok(await admin.getByRole('checkbox', { name: /Room Host/ }).isChecked())
  await admin.getByRole('checkbox', { name: /Candidate/ }).check()
  await admin.getByRole('button', { name: 'Done', exact: true }).click()
  await admin.getByLabel('Search', { exact: true }).fill('Practice')
  await admin.getByLabel('Status', { exact: true }).selectOption('drafted')
  const date = new Date().toISOString().slice(0, 10)
  await admin.getByLabel('Start date').fill(date)
  await admin.getByLabel('End date').fill(date)
  await admin.getByRole('button', { name: 'Apply filters' }).click()
  await admin.getByText('Page 1 of 1 · 25 records', { exact: true }).waitFor()
  await admin.setViewportSize({ width: 375, height: 815 })
  assert.ok(await admin.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await admin.screenshot({ path: resolve(artifacts, 'quizzent-step17-directory.png'), fullPage: true })
  await audit(admin, 'Admin directory mobile')
  await navigation.getByRole('link', { name: 'Admin controls', exact: true }).click()
  const row = admin.getByRole('region', { name: 'Accounts' }).getByRole('listitem').filter({ hasText: candidate.email })
  const suspend = row.getByRole('button', { name: 'Suspend', exact: true })
  await suspend.click()
  const dialog = admin.getByRole('dialog')
  await dialog.getByLabel('Your current password').waitFor()
  await audit(admin, 'Admin confirmation modal mobile')
  await admin.mouse.click(4, 4)
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(await suspend.evaluate(button => button === document.activeElement), true)
  await suspend.click()
  await admin.keyboard.press('Escape')
  await dialog.waitFor({ state: 'hidden' })
  await suspend.click()
  await dialog.getByLabel('Your current password').fill('incorrect')
  await dialog.getByRole('button', { name: 'Suspend account', exact: true }).click()
  await admin.getByRole('button', { name: 'Dismiss notification: The current password is incorrect.', exact: true }).waitFor()
  await dialog.getByLabel('Your current password').fill(password)
  await dialog.getByRole('button', { name: 'Suspend account', exact: true }).click()
  await row.getByText('Suspended', { exact: true }).waitFor()
  await admin.getByRole('button', { name: 'Dismiss notification: The current password is incorrect.', exact: true }).waitFor({ state: 'hidden' })
  await admin.getByRole('button', { name: 'Dismiss notification: Account status saved.', exact: true }).waitFor()
  assert.ok(await row.getByRole('button', { name: 'Make superadmin' }).isDisabled())
  const own = admin.getByRole('region', { name: 'Accounts' }).getByRole('listitem').filter({ hasText: adminAccount.email })
  assert.equal(await own.getByRole('button', { name: 'Suspend', exact: true }).count(), 0)
  // Toasts should leave the viewport automatically and must remain dismissible.
  while (await admin.getByRole('button', { name: 'Dismiss notification' }).count()) await admin.getByRole('button', { name: 'Dismiss notification' }).first().click()
  await row.getByRole('button', { name: 'Reactivate', exact: true }).click()
  await dialog.getByRole('button', { name: 'Reactivate account', exact: true }).click()
  await admin.getByRole('button', { name: 'Dismiss notification: Account status saved.', exact: true }).waitFor()
  await admin.setViewportSize({ width: 1280, height: 900 })
  await admin.bringToFront()
  await admin.mouse.move(370, 800)
  const toast = admin.getByRole('button', { name: 'Dismiss notification: Account status saved.', exact: true })
  const progress = toast.locator('..').locator('[aria-hidden="true"] > span')
  const start = await progress.evaluate(el => el.getBoundingClientRect().width)
  await admin.waitForTimeout(700)
  const shrunk = await progress.evaluate(el => el.getBoundingClientRect().width)
  assert.ok(shrunk < start)
  await toast.hover()
  await progress.evaluate(async element => { await element.getAnimations()[0].ready })
  const frozen = await progress.evaluate(el => el.getBoundingClientRect().width)
  await admin.waitForTimeout(400)
  assert.ok(Math.abs(frozen - await progress.evaluate(el => el.getBoundingClientRect().width)) < 2)
  await admin.screenshot({ path: resolve(artifacts, 'quizzent-refined-notification.png') })
  const bounds = await toast.boundingBox()
  assert.ok(bounds.x > 1280 / 2)
  assert.ok(Math.abs(bounds.x + bounds.width - (1280 - 16)) < 2)
  // The countdown line must not intercept clicks at the bottom of the card.
  await toast.click({ position: { x: 100, y: bounds.height - 2 } })
  await toast.waitFor({ state: 'hidden' })
  await organiser.goto(base + '/organiser/rooms/' + closed.id)
  await organiser.getByText('Room closed', { exact: true }).waitFor()
  assert.equal(await organiser.getByRole('button', { name: 'Refresh participants' }).count(), 0)
  let refreshCalls = 0
  organiser.on('request', request => { if (request.url().endsWith('/api/rooms/' + closed.id)) refreshCalls++ })
  await organiser.waitForTimeout(4500)
  assert.equal(refreshCalls, 0)
  await organiser.goto(base + '/organiser/rooms/' + cancelled.id)
  await organiser.getByRole('heading', { name: 'Competition cancelled' }).waitFor()
  assert.equal(await organiser.getByRole('button', { name: 'Refresh participants' }).count(), 0)
  await organiser.getByRole('button', { name: 'Log out', exact: true }).click()
  await organiser.getByRole('link', { name: /Host a quiz/ }).waitFor()
  await organiser.goto(base + '/signup')
  await organiser.getByRole('button', { name: 'Create organiser account' }).waitFor()
  await audit(organiser, 'Signed-out signup mobile')
  await login(organiser, host.email)
  await audit(organiser, 'Organiser space mobile')
  await organiser.goto(base + '/organiser/competitions/new')
  await organiser.getByLabel('Competition title').fill('Browser hardening journey')
  await organiser.getByLabel('Time per question (seconds)').fill('30')
  await organiser.getByRole('button', { name: 'Create draft', exact: true }).click()
  await organiser.waitForURL('**/organiser')
  await organiser.getByRole('link').filter({ hasText: 'Browser hardening journey' }).click()
  await organiser.getByRole('link', { name: 'Manage questions', exact: true }).click()
  await organiser.getByRole('button', { name: 'Add question', exact: true }).click()
  await organiser.getByLabel('Question', { exact: true }).fill('Which letter comes first?')
  for (const label of ['A', 'B', 'C', 'D']) await organiser.getByLabel('Option ' + label, { exact: true }).fill(label)
  await organiser.getByRole('radio', { name: 'Option A is correct' }).check()
  await audit(organiser, 'Question editor mobile')
  await organiser.getByRole('button', { name: 'Save question', exact: true }).click()
  await organiser.getByRole('button', { name: 'Publish competition', exact: true }).click()
  await organiser.getByRole('dialog').getByRole('button', { name: 'Publish and lock', exact: true }).click()
  await organiser.getByLabel('Lobby countdown (seconds)').fill('0')
  await organiser.getByLabel('Minimum ready guests').fill('1')
  await organiser.getByRole('button', { name: 'Open room', exact: true }).click()
  await organiser.waitForURL('**/organiser/rooms/*')
  await audit(organiser, 'Organiser live room mobile')
  const roomId = organiser.url().split('/').at(-1)
  const { rows: [live] } = await pool.query('SELECT code FROM rooms WHERE id = $1', [roomId])
  const guest = await browser.newPage({ viewport: { width: 375, height: 815 } })
  guest.on('pageerror', error => errors.push(error.message))
  guest.setDefaultTimeout(15_000)
  await guest.goto(base + '/join')
  await guest.getByLabel('Room code', { exact: true }).fill(live.code)
  await guest.getByRole('button', { name: /Find room/ }).click()
  await guest.getByLabel('Your nickname').fill('Browser Guest')
  await audit(guest, 'Guest join mobile')
  await guest.getByRole('button', { name: 'Join room', exact: true }).click()
  await guest.getByRole('button', { name: 'I’m ready', exact: true }).waitFor({ state: 'visible' })
  await audit(guest, 'Guest lobby mobile')
  await guest.getByRole('button', { name: 'I’m ready', exact: true }).click()
  await guest.getByRole('heading', { name: 'Which letter comes first?', exact: true }).waitFor()
  await audit(guest, 'Guest timed question mobile')
  await guest.getByRole('radio').first().check()
  await guest.getByRole('button', { name: /Submit answer/ }).click()
  await guest.getByRole('heading', { name: 'Final leaderboard', exact: true }).waitFor()
  await audit(guest, 'Guest final results mobile')
  await guest.reload()
  await guest.getByRole('heading', { name: 'Final leaderboard', exact: true }).waitFor()
  await guest.screenshot({ path: resolve(artifacts, 'quizzent-step18-results.png'), fullPage: true })
  assert.deepEqual(errors, [])
  console.log('Browser and accessibility checks passed: navigation, demo and reduced motion, identical favicon, multiselect and 10/25 row pagination, modal dismissal/focus, suspension password, disappearing notifications, closed-room requests, and logout.')
} catch (error) {
  console.error(error)
  if (browser) {
    for (const context of browser.contexts()) for (const page of context.pages()) {
      console.error('Page', page.url(), (await page.locator('body').innerText()).slice(-2000))
    }
  }
  throw error
} finally {
  await browser?.close()
  await vite?.close()
  await runtime?.close()
  await pool?.end()
  try { await db.query('DROP SCHEMA IF EXISTS "' + schema + '" CASCADE') }
  finally { await db.end() }
}
